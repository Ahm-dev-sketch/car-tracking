export type IconName = keyof typeof icons;

export function Icon({
  name,
  strokeWidth,
  ...props
}: SVGProps<SVGSVGElement> & { name: IconName }) {
  const Glyph = icons[name] ?? CircleDot;
  return (
    <Glyph
      width={20}
      height={20}
      strokeWidth={strokeWidth ?? 1.75}
      aria-hidden="true"
      focusable="false"
      {...props}
    />
  );
}
